        if paths != tuple(sorted(paths, key=lambda item: item.encode("utf-8"))) or len(paths) != len(set(paths)):
            raise ValueError("runner source manifest must be unique and path-sorted")
        if "pyproject.toml" not in paths or any(
            path != "pyproject.toml" and not path.startswith("kirby2/") for path in paths
        ):
            raise ValueError("runner source lock projection is outside kirby2 plus pyproject")
        expected = hashlib.sha256(
            canonical_json_bytes([item.as_dict() for item in self.source_manifest])
        ).hexdigest()
