def _series_object(value: object, label: str) -> dict[str, tuple[int, ...]]:
    if type(value) is not dict or any(type(key) is not str for key in value):
        raise TypeError(f"{label} must be a string-keyed object")
    series: dict[str, tuple[int, ...]] = {}
    for key, items in value.items():
        metric_id = _text(key, f"{label} metric ID", 128)
        series[metric_id] = tuple(
            _nonnegative_integer(item, f"{metric_id} sample")
            for item in _array(items, f"{metric_id} samples")
        )
    return series


def _reduce_series(values: tuple[int, ...], statistic: str) -> int:
    if statistic == "MAX":
        if not values:
            raise ValueError("MAX reduction requires samples")
        return max(values)
    percentile = {"P50": 500_000, "P95": 950_000, "P99": 990_000}.get(
        statistic
    )
    if percentile is None:
        raise ValueError("auxiliary reduction statistic is unsupported")
    return nearest_rank(values, percentile)


@dataclass(frozen=True, slots=True)
class ReleaseAuxiliaryPerformanceResultV1:
    workload_id: str
    status: str
    provenance: dict[str, object]
    warmup_series: dict[str, tuple[int, ...]]
    measured_series: dict[str, tuple[int, ...]]
    reductions: tuple[dict[str, object], ...]
    threshold_results: tuple[dict[str, object], ...]
    hard_failure_codes: tuple[str, ...]
    evidence_records: tuple[dict[str, object], ...]
    schema_version: int = 1

    def __post_init__(self) -> None:
        if type(self.schema_version) is not int or self.schema_version != 1:
            raise ValueError("auxiliary result schema version differs")
        _text(self.workload_id, "auxiliary workload ID", 128)
        _text(self.status, "auxiliary result status", 64)
        if self.workload_id not in _AUXILIARY_SAMPLE_COUNTS_V1:
            raise ValueError("auxiliary result workload ID is invalid")
        if self.status not in {"PASS", "WARNING", "FAIL"}:
            raise ValueError("auxiliary result status is invalid")
        if type(self.provenance) is not dict:
            raise TypeError("auxiliary provenance must be an object")
        if type(self.warmup_series) is not dict or type(self.measured_series) is not dict:
            raise TypeError("auxiliary sample series must be objects")
        if type(self.reductions) is not tuple or type(self.threshold_results) is not tuple:
            raise TypeError("auxiliary reductions and thresholds must be tuples")
        if type(self.hard_failure_codes) is not tuple:
            raise TypeError("auxiliary hard-failure codes must be a tuple")
        for code in self.hard_failure_codes:
            _text(code, "auxiliary hard-failure code", 256)
        if self.hard_failure_codes != tuple(
            sorted(set(self.hard_failure_codes), key=lambda item: item.encode("utf-8"))
        ):
            raise ValueError("auxiliary hard-failure codes must be unique and UTF-8 sorted")
        self._validate_provenance()
        self._validate_samples()
        self._validate_reductions_and_thresholds()
        if type(self.evidence_records) is not tuple:
            raise TypeError("auxiliary evidence records must be a tuple")
        evidence_ids: list[str] = []
        for raw in self.evidence_records:
            row = _exact_object(
                raw,
                {"evidence_id", "size", "sha256"},
                "auxiliary evidence record",
            )
            evidence_id = _text(row["evidence_id"], "auxiliary evidence ID", 256)
            _nonnegative_integer(row["size"], "auxiliary evidence size")
            require_sha256(row["sha256"], "auxiliary evidence digest")
            evidence_ids.append(evidence_id)
        if evidence_ids != sorted(evidence_ids, key=lambda item: item.encode("utf-8")) or len(
            evidence_ids
        ) != len(set(evidence_ids)):
            raise ValueError("auxiliary evidence records must be unique and ID-sorted")

    def _validate_provenance(self) -> None:
        row = _exact_object(
            self.provenance,
            {
                "candidate_commit",
                "source_manifest_sha256",
                "entrypoint_sources",
                "artifact_manifest_sha256",
                "asset_manifest_sha256",
                "input_identity_sha256",
            },
            "auxiliary provenance",
        )
        candidate = _text(row["candidate_commit"], "auxiliary candidate commit", 40)
        if _COMMIT.fullmatch(candidate) is None:
            raise ValueError("auxiliary candidate commit is invalid")
        for field in (
            "source_manifest_sha256",
            "artifact_manifest_sha256",
            "input_identity_sha256",
        ):
            require_sha256(row[field], f"auxiliary {field}")
        asset_digest = row["asset_manifest_sha256"]
        if self.workload_id == "RELEASE_MICROSCOPE_LOAD_V1":
            require_sha256(asset_digest, "microscope asset-manifest digest")
        elif asset_digest is not None:
            raise ValueError("non-microscope auxiliary result carries an asset digest")
        sources = _array(row["entrypoint_sources"], "auxiliary entrypoint sources")
        for source in sources:
            item = _exact_object(
                source, {"path", "sha256"}, "auxiliary entrypoint source"
            )
            _repository_source_path(item["path"], "auxiliary entrypoint path")
            require_sha256(item["sha256"], "auxiliary entrypoint digest")

    def _validate_samples(self) -> None:
        warmup_counts, measured_counts = _AUXILIARY_SAMPLE_COUNTS_V1[self.workload_id]
        if set(self.warmup_series) != set(warmup_counts):
            raise ValueError("auxiliary warmup metric keys differ")
        if set(self.measured_series) != set(measured_counts):
            raise ValueError("auxiliary measured metric keys differ")
        for series, counts, label in (
            (self.warmup_series, warmup_counts, "warmup"),
            (self.measured_series, measured_counts, "measured"),
        ):
            for metric_id, expected_count in counts.items():
                values = series[metric_id]
                if type(values) is not tuple or any(
                    type(item) is not int or item < 0 for item in values
                ):
                    raise ValueError(f"auxiliary {label} series is not nonnegative integers")
                if len(values) > expected_count or (
                    self.status in {"PASS", "WARNING"}
                    and len(values) != expected_count
                ):
                    raise ValueError(f"auxiliary {label} sample count differs")

    def _validate_reductions_and_thresholds(self) -> None:
        reduction_order = _AUXILIARY_REDUCTION_ORDER_V1[self.workload_id]
        if len(self.reductions) != len(reduction_order) or len(
            self.threshold_results
        ) != len(reduction_order):
            raise ValueError("auxiliary reduction/threshold cardinality differs")
        observed_statuses: list[str] = []
        for reduction_id, raw_reduction, raw_threshold in zip(
            reduction_order,
            self.reductions,
            self.threshold_results,
            strict=True,
        ):
            protocol = _AUXILIARY_THRESHOLD_BY_ID_V1[reduction_id]
            reduction = _exact_object(
                raw_reduction,
                {
                    "reduction_id",
                    "metric_id",
                    "statistic",
                    "value",
                    "unit",
                    "availability",
                },
                "auxiliary reduction",
            )
            if (
                reduction["reduction_id"] != reduction_id
                or reduction["metric_id"] != protocol["metric_id"]
                or reduction["statistic"] != protocol["statistic"]
                or reduction["unit"]
                != _AUXILIARY_METRIC_UNITS_V1[protocol["metric_id"]]  # type: ignore[index]
            ):
                raise ValueError("auxiliary reduction identity differs")
            availability = reduction["availability"]
            metric_id = protocol["metric_id"]
            values = self.measured_series[metric_id]  # type: ignore[index]
            expected_count = _AUXILIARY_SAMPLE_COUNTS_V1[self.workload_id][1][metric_id]  # type: ignore[index]
            complete = len(values) == expected_count
            if availability == "AVAILABLE":
                if not complete:
                    raise ValueError("auxiliary reduction claims incomplete samples")
                expected_value = _reduce_series(values, protocol["statistic"])  # type: ignore[arg-type]
                if reduction["value"] != expected_value:
                    raise ValueError("auxiliary reduction value does not reconcile")
            elif availability == "UNAVAILABLE":
                if complete or reduction["value"] is not None:
                    raise ValueError("auxiliary unavailable reduction is inconsistent")
            else:
                raise ValueError("auxiliary reduction availability is invalid")

            threshold = _exact_object(
                raw_threshold,
                {
                    "reduction_id",
                    "metric_id",
                    "statistic",
                    "status",
                    "pass_upper_inclusive",
                    "warning_upper_inclusive",
                    "hard_failure",
                    "reason_code",
                },
                "auxiliary threshold result",
            )
            for field in (
                "reduction_id",
                "metric_id",
                "statistic",
                "pass_upper_inclusive",
                "warning_upper_inclusive",
                "hard_failure",
            ):
                if threshold[field] != protocol[field]:
                    raise ValueError("auxiliary threshold protocol binding differs")
            if type(threshold["hard_failure"]) is not bool:
                raise TypeError("auxiliary threshold hard-failure flag must be Boolean")
            if availability == "UNAVAILABLE":
                if threshold["status"] != "NOT_EVALUATED" or threshold[
                    "reason_code"
                ] not in {"INCOMPLETE_SAMPLES", "UPSTREAM_HARD_FAILURE"}:
                    raise ValueError("auxiliary unavailable threshold is inconsistent")
            else:
                value = reduction["value"]
                if type(value) is not int or value < 0:
                    raise ValueError("available auxiliary reduction lacks an integer value")
                if value <= protocol["pass_upper_inclusive"]:  # type: ignore[operator]
                    expected_status, expected_reason = "PASS", None
                elif value <= protocol["warning_upper_inclusive"]:  # type: ignore[operator]
                    expected_status, expected_reason = "WARNING", None
                elif reduction_id == "TERMINAL_UPDATE_MAX":
                    expected_status = "FAIL"
                    expected_reason = "TERMINAL_UPDATE_PAUSE_OVER_500_MS"
                else:
                    expected_status, expected_reason = "FAIL", "THRESHOLD_MISS"
                if (
                    threshold["status"] != expected_status
                    or threshold["reason_code"] != expected_reason
                ):
                    raise ValueError("auxiliary threshold result does not reconcile")
                if protocol["hard_failure"] and expected_status == "FAIL" and (
                    expected_reason not in self.hard_failure_codes
                ):
                    raise ValueError("hard auxiliary threshold failure lacks its code")
            observed_statuses.append(threshold["status"])  # type: ignore[arg-type]

        expected_overall = (
            "FAIL"
            if self.hard_failure_codes
            or any(item in {"FAIL", "NOT_EVALUATED"} for item in observed_statuses)
            else (
                "WARNING" if "WARNING" in observed_statuses else "PASS"
            )
        )
        if self.status != expected_overall:
            raise ValueError("auxiliary overall status does not reconcile")

