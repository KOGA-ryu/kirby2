def round_div_even(numerator: int, denominator: int) -> int:
    if type(numerator) is not int or type(denominator) is not int or denominator <= 0:
        raise ValueError("round_div_even requires integers and a positive denominator")
    quotient, remainder = divmod(abs(numerator), denominator)
    if 2 * remainder > denominator or (
        2 * remainder == denominator and quotient % 2 == 1
    ):
        quotient += 1
    return -quotient if numerator < 0 else quotient


def labeled_simulation_seed(root_seed: int, policy_version: str, label: str) -> int:
    if type(root_seed) is not int or not 0 <= root_seed <= (1 << 63) - 1:
        raise ValueError("labeled seed root must be a nonnegative signed-u64 value")
    for value, name in ((policy_version, "policy version"), (label, "label")):
        if type(value) is not str or not value or unicodedata.normalize("NFC", value) != value:
            raise ValueError(f"labeled seed {name} must be nonempty NFC text")
    digest = hashlib.sha256(
        root_seed.to_bytes(8, "big")
        + b"\0"
        + policy_version.encode("utf-8")
        + b"\0"
        + label.encode("utf-8")
    ).digest()
    return int.from_bytes(digest[:8], "big") & ((1 << 63) - 1)


def fixed_decimal(value: str | Decimal) -> dict[str, int]:
    decimal = value if isinstance(value, Decimal) else Decimal(value)
    if not decimal.is_finite():
        raise ValueError("release fixed decimal must be finite")
    scaled = decimal * FIXED_SCALE_V1
    if scaled != scaled.to_integral_value():
        raise ValueError("release fixed decimal exceeds six places")
    return {"fixed_decimal_micros": int(scaled)}


def release_native_fixed_point(value: object) -> object:
    """Project a constructor tree whose decimals are explicit ``Decimal`` values."""

    if value is None or type(value) in {bool, int, str}:
        if type(value) is str and unicodedata.normalize("NFC", value) != value:
            raise ValueError("native fixed-point text must be NFC")
        return value
    if isinstance(value, Decimal):
        return fixed_decimal(value)
    if type(value) is float:
        raise TypeError("binary floats cannot enter native fixture identity")
    if type(value) in {list, tuple}:
        return [release_native_fixed_point(item) for item in value]
    if type(value) is dict:
        if any(type(key) is not str for key in value):
            raise TypeError("native fixed-point maps require string keys")
        return {
            key: release_native_fixed_point(value[key])
            for key in sorted(value, key=lambda item: item.encode("utf-8"))
        }
    raise TypeError(f"unsupported native fixture value: {type(value).__name__}")


def release_float_free_semantic(value: object) -> object:
    """Project all identity-bearing native numbers without JSON floats."""

    if value is None or type(value) in {bool, int}:
        return value
    if type(value) is str:
        if unicodedata.normalize("NFC", value) != value:
            raise ValueError("release semantic text must be NFC")
        return value
    if type(value) is float:
        if not math.isfinite(value) or (value == 0.0 and math.copysign(1.0, value) < 0):
            raise ValueError("release semantic projection forbids nonfinite/negative zero")
        numerator, denominator = value.as_integer_ratio()
        return {
            _SCALAR_RESERVED: "EXACT_RATIONAL",
            "denominator": denominator,
            "numerator": numerator,
        }
    if isinstance(value, Decimal):
        if not value.is_finite() or value.is_zero() and value.is_signed():
            raise ValueError("release semantic Decimal is invalid")
        normalized = value.normalize()
        sign, digits, exponent = normalized.as_tuple()
        coefficient = int("".join(str(item) for item in digits) or "0")
        if sign:
            coefficient = -coefficient
        return {
            _SCALAR_RESERVED: "EXACT_DECIMAL",
            "coefficient": coefficient,
            "exponent": exponent,
        }
    if type(value) in {list, tuple}:
        return [release_float_free_semantic(item) for item in value]
    if type(value) is dict:
        if _SCALAR_RESERVED in value:
            raise ValueError("release semantic source uses the reserved scalar key")
        if any(type(key) is not str or unicodedata.normalize("NFC", key) != key for key in value):
            raise ValueError("release semantic maps require unique NFC string keys")
        return {
            key: release_float_free_semantic(value[key])
            for key in sorted(value, key=lambda item: item.encode("utf-8"))
        }
    raise TypeError(f"unsupported release semantic value: {type(value).__name__}")


def _pointer_token(value: str) -> str:
    return value.replace("~", "~0").replace("/", "~1")


def extract_legacy_digest_bindings(value: object) -> tuple[object, tuple[dict[str, str], ...]]:
    """Replace every legacy lowercase SHA string by an RFC-6901 pointer reference."""

    bindings: list[dict[str, str]] = []

    def visit(item: object, pointer: str) -> object:
        if type(item) is str and _SHA256.fullmatch(item) is not None:
            bindings.append({"json_pointer": pointer, "legacy_sha256": item})
            return {_LEGACY_RESERVED: pointer}
        if type(item) is list:
            return [visit(child, f"{pointer}/{index}") for index, child in enumerate(item)]
        if type(item) is dict:
            if _LEGACY_RESERVED in item:
                raise ValueError("legacy source uses the reserved digest-reference key")
            if any(
                type(key) is not str or unicodedata.normalize("NFC", key) != key
                for key in item
            ):
                raise ValueError("legacy source maps require NFC string keys")
            return {
                key: visit(item[key], f"{pointer}/{_pointer_token(key)}")
                for key in sorted(item, key=lambda value: value.encode("utf-8"))
            }
        return item

    projected = visit(value, "")
    ordered = tuple(
        sorted(bindings, key=lambda item: item["json_pointer"].encode("utf-8"))
    )
    return projected, ordered


