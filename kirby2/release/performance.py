@dataclass(frozen=True, slots=True)
class ReleasePerformanceRowTemplateV1:
    work_unit_id: str
    cell: str
    root_seed: int
    generated_configuration: dict[str, object]
    generated_configuration_sha256: str
    native_fixture_template: dict[str, object]
    runner_id: str
    expected_capabilities: tuple[str, ...]
    required_checks: tuple[str, ...]
    audit_argv: dict[str, list[str]]
    artifact_form: str
    initial_attempt: int = 1
    runner_source_policy_id: str = RELEASE_RUNNER_SOURCE_POLICY_ID_V1
    result_schema_id: str = RELEASE_PERFORMANCE_RESULT_SCHEMA_ID_V1

    schema_id: ClassVar[str] = RELEASE_PERFORMANCE_ROW_TEMPLATE_SCHEMA_ID_V1
    schema_version: ClassVar[int] = 1

    def __post_init__(self) -> None:
        try:
            cell = ReleasePerformanceCellV1(self.cell)
        except ValueError as error:
            raise ValueError("release performance row cell is invalid") from error
        if type(self.root_seed) is not int or self.root_seed not in RELEASE_PERFORMANCE_ROOTS_V1:
            raise ValueError("release performance row root is outside its range")
        if self.work_unit_id != f"release-perf/{cell.value}/{self.root_seed}":
            raise ValueError("release performance work-unit ID differs")
        spec = _CELL_SPECS_V1[RELEASE_PERFORMANCE_CELL_ORDER_V1.index(cell)]
        if (
            self.runner_id != spec.runner_id
            or self.artifact_form != spec.artifact_form
            or self.expected_capabilities != spec.expected_capabilities
            or self.required_checks != spec.required_checks
        ):
            raise ValueError("release performance runner contract differs")
        if type(self.initial_attempt) is not int or self.initial_attempt != 1:
            raise ValueError("release performance initial attempt must be one")
        if self.runner_source_policy_id != RELEASE_RUNNER_SOURCE_POLICY_ID_V1:
            raise ValueError("release performance source policy differs")
        if self.result_schema_id != RELEASE_PERFORMANCE_RESULT_SCHEMA_ID_V1:
            raise ValueError("release performance result schema differs")
        if type(self.generated_configuration) is not dict:
            raise TypeError("generated configuration must be an object")
        if release_float_free_semantic(self.generated_configuration) != self.generated_configuration:
            raise ValueError("generated configuration is not float-free semantic JSON")
        if hashlib.sha256(canonical_json_bytes(self.generated_configuration)).hexdigest() != self.generated_configuration_sha256:
            raise ValueError("generated configuration digest differs")
        if (
            self.generated_configuration.get("seed") is None
            or self.generated_configuration.get("cell_id")
            != f"release-{cell.value.lower().replace('_', '-')}-{self.root_seed - RELEASE_PERFORMANCE_ROOTS_V1.start:04d}"
        ):
            raise ValueError("generated configuration identity differs")
        if type(self.native_fixture_template) is not dict or set(
            self.native_fixture_template
        ) != {
            "constructor_id",
            "fixture_id",
            "generated_configuration_sha256",
            "parameters",
            "schema_version",
        }:
            raise ValueError("native fixture template fields differ")
        if (
            self.native_fixture_template["constructor_id"] != spec.constructor_id
            or self.native_fixture_template["fixture_id"] != f"{cell.value}_FIXTURE_V1"
            or self.native_fixture_template["schema_version"] != 1
        ):
            raise ValueError("native fixture template identity differs")
        if self.native_fixture_template.get("generated_configuration_sha256") != self.generated_configuration_sha256:
            raise ValueError("native fixture does not bind its generated configuration")
        if release_float_free_semantic(self.native_fixture_template) != self.native_fixture_template:
            raise ValueError("native fixture template is not float-free semantic JSON")
        if set(self.audit_argv) != {"1", "2"}:
            raise ValueError("release performance audit argv must declare two attempts")
        expected_argv = {
            str(attempt): [
                "kirby2",
                "qualify-performance-row",
                "--protocol",
                "release/performance_thresholds.toml",
                "--work-unit-id",
                self.work_unit_id,
                "--attempt",
                str(attempt),
            ]
            for attempt in (1, 2)
        }
        if self.audit_argv != expected_argv:
            raise ValueError("release performance audit argv differs")

    def as_dict(self) -> dict[str, object]:
        return {
            "artifact_form": self.artifact_form,
            "audit_argv": self.audit_argv,
            "cell": self.cell,
            "expected_capabilities": list(self.expected_capabilities),
            "generated_configuration": self.generated_configuration,
            "generated_configuration_sha256": self.generated_configuration_sha256,
            "initial_attempt": self.initial_attempt,
            "native_fixture_template": self.native_fixture_template,
            "required_checks": list(self.required_checks),
            "result_schema_id": self.result_schema_id,
            "root_seed": self.root_seed,
            "runner_id": self.runner_id,
            "runner_source_policy_id": self.runner_source_policy_id,
            "work_unit_id": self.work_unit_id,
        }

    def canonical_bytes(self) -> bytes:
        return canonical_json_bytes(self.as_dict())

    @property
    def sha256(self) -> str:
        return hashlib.sha256(self.canonical_bytes()).hexdigest()


def build_performance_row_template(
    cell: ReleasePerformanceCellV1 | str, root_seed: int
) -> ReleasePerformanceRowTemplateV1:
    selected = cell if isinstance(cell, ReleasePerformanceCellV1) else ReleasePerformanceCellV1(cell)
    spec = _CELL_SPECS_V1[RELEASE_PERFORMANCE_CELL_ORDER_V1.index(selected)]
    configuration = _generated_configuration(spec, root_seed)
    configuration_digest = hashlib.sha256(canonical_json_bytes(configuration)).hexdigest()
    fixture = {
        "constructor_id": spec.constructor_id,
        "fixture_id": f"{selected.value}_FIXTURE_V1",
        "generated_configuration_sha256": configuration_digest,
        "parameters": _native_parameters(spec, configuration),
        "schema_version": 1,
    }
    work_unit_id = f"release-perf/{selected.value}/{root_seed}"
    argv = {
        str(attempt): [
            "kirby2",
            "qualify-performance-row",
            "--protocol",
            "release/performance_thresholds.toml",
            "--work-unit-id",
            work_unit_id,
            "--attempt",
            str(attempt),
        ]
        for attempt in (1, 2)
    }
    return ReleasePerformanceRowTemplateV1(
        work_unit_id=work_unit_id,
        cell=selected.value,
        root_seed=root_seed,
        generated_configuration=configuration,
        generated_configuration_sha256=configuration_digest,
        native_fixture_template=fixture,
        runner_id=spec.runner_id,
        expected_capabilities=spec.expected_capabilities,
        required_checks=spec.required_checks,
        audit_argv=argv,
        artifact_form=spec.artifact_form,
    )


def iter_performance_row_templates() -> Iterable[ReleasePerformanceRowTemplateV1]:
    for cell in RELEASE_PERFORMANCE_CELL_ORDER_V1:
        for root_seed in RELEASE_PERFORMANCE_ROOTS_V1:
            yield build_performance_row_template(cell, root_seed)


def performance_row_corpus_sha256() -> str:
    """Hash the canonical ordered array without retaining all rows in memory."""

    digest = hashlib.sha256()
    digest.update(b"[")
    for ordinal, row in enumerate(iter_performance_row_templates()):
        if ordinal:
            digest.update(b",")
        digest.update(row.canonical_bytes())
    digest.update(b"]")
    return digest.hexdigest()


