def performance_semantic_artifact_set(
    members: Mapping[str, bytes],
) -> tuple[tuple[dict[str, object], ...], str]:
    if type(members) is not dict or tuple(members) != _SEMANTIC_ARTIFACT_NAMES_V1:
        raise ValueError("performance semantic artifact members or order differ")
    rows: list[dict[str, object]] = []
    for name in _SEMANTIC_ARTIFACT_NAMES_V1:
        raw = members[name]
        _load_canonical_json(raw, f"performance artifact {name}")
        rows.append(
            {
                "name": name,
                "sha256": hashlib.sha256(raw).hexdigest(),
                "size": len(raw),
            }
        )
    projection = tuple(rows)
    return projection, hashlib.sha256(canonical_json_bytes(rows)).hexdigest()


