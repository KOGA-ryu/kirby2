def validate_performance_attempt_sequence(
    attempts: tuple[ReleasePerformanceCellResultV1, ...],
) -> None:
    if (
        type(attempts) is not tuple
        or not 1 <= len(attempts) <= 2
        or any(type(item) is not ReleasePerformanceCellResultV1 for item in attempts)
    ):
        raise TypeError("performance attempt sequence must contain one or two typed results")
    first = attempts[0]
    if first.attempt != 1:
        raise ValueError("performance attempt sequence must begin at attempt one")
    if len(attempts) == 1:
        return
    second = attempts[1]
    if (
        first.status != "FAILED"
        or first.failure_code not in {"PROCESS_FAILURE", "RESOURCE_LIMIT"}
        or second.attempt != 2
    ):
        raise ValueError("performance retry is not authorized by attempt one")
    identities = (
        "work_unit_id",
        "generated_configuration_sha256",
        "native_fixture_sha256",
        "runner_source_sha256",
    )
    if any(getattr(first, field) != getattr(second, field) for field in identities):
        raise ValueError("performance retry identity differs from attempt one")
    semantic_fields = (
        "run_manifest_sha256",
        "native_recording_sha256",
        "semantic_result_sha256",
        "artifact_set_sha256",
        "audit_result_sha256",
    )
    for field in semantic_fields:
        first_digest = getattr(first, field)
        second_digest = getattr(second, field)
        if (
            first_digest is not None
            and second_digest is not None
            and first_digest != second_digest
        ):
            raise ValueError("performance retry changed a completed semantic artifact")


